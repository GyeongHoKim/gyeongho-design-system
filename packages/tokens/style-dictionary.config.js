/**
 * @ghds/tokens — Style Dictionary v4 multi-platform build.
 *
 * Source: W3C DTCG tokens in `src/{ref,sys,comp}`. References are resolved by
 * Style Dictionary; this script then emits four platform shapes into `dist/`:
 *
 *   - css   → `dist/css/variables.css`  (:root light + [data-theme="dark"] + prefers-color-scheme)
 *   - ts    → `dist/ts/{light,dark}.{js,d.ts}` + `dist/index.{js,d.ts}` (web, value strings)
 *   - rn    → `dist/rn/{light,dark}.{js,d.ts}` + `dist/rn/index.{js,d.ts}` (px/ms → numbers,
 *             font stacks → per-platform, per-weight family names)
 *   - json  → `dist/json/tokens.json` + `dist/json/tokens.dark.json` (platform-agnostic, resolved)
 *
 * Every output PRESERVES the semantic token path: CSS uses `--{path-with-dashes}`,
 * the JS/JSON/RN objects keep the original nested keys (`tokens.sys.color.bg.primary.default`).
 */
import { promises as fs, readFileSync } from 'node:fs';
import path from 'node:path';
import StyleDictionary from 'style-dictionary';

const HEADER =
  '/**\n * GHDS design tokens — GENERATED by @ghds/tokens build. Do not edit by hand.\n */\n';
const THEMES = ['light', 'dark'];

/** Build a nested plain object of resolved values keyed by each token's semantic path. */
function buildNested(allTokens) {
  const root = {};
  for (const token of allTokens) {
    const segs = token.path;
    let node = root;
    for (let i = 0; i < segs.length; i++) {
      const seg = segs[i];
      if (i === segs.length - 1) {
        node[seg] = token.$value;
      } else {
        node[seg] ??= {};
        node = node[seg];
      }
    }
  }
  return root;
}

/** Render a nested value object as a precise TypeScript literal type. */
function toDts(value, indent = '  ') {
  if (value === null || typeof value !== 'object') {
    return typeof value === 'number' ? String(value) : JSON.stringify(value);
  }
  const next = `${indent}  `;
  const entries = Object.entries(value).map(
    ([key, child]) => `${next}readonly ${JSON.stringify(key)}: ${toDts(child, next)};`,
  );
  return `{\n${entries.join('\n')}\n${indent}}`;
}

/** Strip a length/duration unit (`16px` → 16, `200ms` → 200); pass through otherwise. */
function rnNumber(value) {
  const px = /^(-?\d*\.?\d+)px$/.exec(value);
  if (px) return Number(px[1]);
  const ms = /^(-?\d*\.?\d+)ms$/.exec(value);
  if (ms) return Number(ms[1]);
  return value;
}

/**
 * Convert a CSS `box-shadow` string into a React Native shadow object that RN can
 * actually consume (`shadowColor`/`shadowOffset`/`shadowOpacity`/`shadowRadius` for iOS,
 * `elevation` for Android). Input shape: `<x> <y> <blur> <spread> rgba(r, g, b, a)`.
 */
function rnShadow(value) {
  const rgba = /rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(?:,\s*([\d.]+)\s*)?\)/.exec(value);
  const lengths = value
    .replace(/rgba?\([^)]*\)/, '')
    .trim()
    .split(/\s+/)
    .map((part) => rnNumber(part));
  const [x = 0, y = 0, blur = 0] = lengths;
  const toHex = (n) => Number(n).toString(16).padStart(2, '0');
  const shadowColor = rgba ? `#${toHex(rgba[1])}${toHex(rgba[2])}${toHex(rgba[3])}` : '#000000';
  const shadowOpacity = rgba?.[4] !== undefined ? Number(rgba[4]) : 1;
  return {
    shadowColor,
    shadowOffset: { width: x, height: y },
    shadowOpacity,
    shadowRadius: blur,
    elevation: Math.round(blur),
  };
}

/**
 * React Native does not support CSS comma-separated font stacks — `fontFamily`
 * accepts a single family name. The RN build replaces each GHDS web stack with
 * one face that covers both Latin and Korean glyphs (RN cannot do per-glyph
 * fallback across families), so the Korean face is preferred for body/UI and
 * display:
 *
 *   sketch → Gaegu        (hand-drawn Korean, also covers Latin)
 *   sans   → Noto Sans KR (Korean sans, also covers Latin; Pretendard fontsource
 *            ships Latin only so cannot serve as the RN Korean face)
 *   mono   → Menlo on iOS, the `monospace` system face on Android (Android has
 *            no Menlo)
 *
 * Each stack becomes a **face table** `{ ios, android }`. Each platform maps
 * every `ref.fontWeight` value (`"400"`, `"500"`, `"700"`) to a weight-specific
 * family name such as `NotoSansKR-Medium`. These are the fonts' PostScript
 * names, which Expo also recommends as file names, so they resolve with the
 * `expo-font` config plugin and bare RN asset linking (file name on Android,
 * PostScript name on iOS) as well as with runtime `useFonts` on any Expo SDK.
 *
 * One family name per weight means the RN theme never needs `fontWeight` to
 * pick a face. Android looks up `<name>_bold.ttf` when a custom font is asked
 * for bold, so the theme leaves `fontWeight` out on native platforms.
 *
 * `faces` lists the files each face actually ships. A weight a face lacks
 * resolves to the nearest available file with the CSS font-matching rule, so a
 * new `ref.fontWeight` never yields a missing name. `ios` / `android` replace
 * `faces` when the platforms differ.
 *
 * The map is keyed by stack name and resolved against the source stacks in
 * `src/ref/typography.json`, so editing a stack never silently breaks the RN
 * mapping. A stack missing from this map uses its first quoted family name for
 * every platform and weight.
 */
const RN_FONT_FACES_BY_STACK = {
  sketch: { faces: { 400: 'Gaegu-Regular', 700: 'Gaegu-Bold' } },
  sans: {
    faces: { 400: 'NotoSansKR-Regular', 500: 'NotoSansKR-Medium', 700: 'NotoSansKR-Bold' },
  },
  mono: {
    ios: { 400: 'Menlo-Regular', 700: 'Menlo-Bold' },
    android: { 400: 'monospace' },
  },
};

const SOURCE_TYPOGRAPHY = JSON.parse(
  readFileSync(new URL('./src/ref/typography.json', import.meta.url), 'utf8'),
).ref;
const SOURCE_FONT_STACKS = SOURCE_TYPOGRAPHY.fontFamily;
const RN_FONT_WEIGHTS = Object.entries(SOURCE_TYPOGRAPHY.fontWeight)
  .filter(([key]) => !key.startsWith('$'))
  .map(([, token]) => Number(token.$value))
  .sort((a, b) => a - b);

/**
 * Pick the available weight for a requested one with the CSS font-matching
 * rule: 400 tries 500 first and 500 tries 400 first; then weights up to 500
 * prefer lighter faces and weights above 500 prefer heavier faces.
 */
function nearestWeight(requested, available) {
  if (available.includes(requested)) return requested;
  if (requested === 400 && available.includes(500)) return 500;
  if (requested === 500 && available.includes(400)) return 400;
  const lighter = available.filter((w) => w < requested).sort((a, b) => b - a);
  const heavier = available.filter((w) => w > requested).sort((a, b) => a - b);
  return requested <= 500 ? (lighter[0] ?? heavier[0]) : (heavier[0] ?? lighter[0]);
}

/** Expand a `{ weight: family }` file list to every `ref.fontWeight` value. */
function rnWeightTable(faces, label) {
  const available = Object.keys(faces).map(Number);
  if (available.length === 0) throw new Error(`RN font map: ${label} lists no faces`);
  return Object.fromEntries(
    RN_FONT_WEIGHTS.map((weight) => [String(weight), faces[nearestWeight(weight, available)]]),
  );
}

/** Expand a stack's face entry to the emitted `{ ios, android }` face table. */
function rnFaceTable(entry, label) {
  const ios = entry.ios ?? entry.faces;
  const android = entry.android ?? entry.faces;
  if (!ios || !android) throw new Error(`RN font map: ${label} needs faces or ios + android`);
  return {
    ios: rnWeightTable(ios, `${label}.ios`),
    android: rnWeightTable(android, `${label}.android`),
  };
}

const RN_FONT_FAMILY_MAP = new Map();
for (const [stack, entry] of Object.entries(RN_FONT_FACES_BY_STACK)) {
  const value = SOURCE_FONT_STACKS[stack]?.$value;
  if (typeof value !== 'string') {
    throw new Error(`RN font map: ref.fontFamily.${stack} is missing from typography.json`);
  }
  // The transform only sees resolved values, so two stacks with the same value
  // cannot map to different RN faces. Fail the build instead of letting one
  // mapping silently overwrite the other.
  const table = rnFaceTable(entry, stack);
  const existing = RN_FONT_FAMILY_MAP.get(value);
  if (existing !== undefined && JSON.stringify(existing) !== JSON.stringify(table)) {
    throw new Error(
      `RN font map: ref.fontFamily.${stack} has the same value as another stack but maps to different RN faces`,
    );
  }
  RN_FONT_FAMILY_MAP.set(value, table);
}

/** Convert a CSS font stack into the RN `{ ios, android }` weight → family table. */
function rnFontFamily(value) {
  const mapped = RN_FONT_FAMILY_MAP.get(value);
  if (mapped) return structuredClone(mapped);
  // Fallback: first quoted name, or first token before a comma, for every weight.
  const quoted = /'([^']+)'/.exec(value);
  const family = quoted ? quoted[1] : value.split(',')[0].trim();
  return rnFaceTable({ faces: { 400: family } }, value);
}

StyleDictionary.registerTransform({
  name: 'ghds/value/rn',
  type: 'value',
  transitive: true,
  filter: (token) => typeof token.$value === 'string',
  transform: (token) => {
    if (token.$type === 'shadow') return rnShadow(token.$value);
    if (token.$type === 'fontFamily') return rnFontFamily(token.$value);
    return rnNumber(token.$value);
  },
});

/**
 * A token's CSS value with `{a.b.c}` aliases preserved as `var(--a-b-c)`
 * references instead of resolved to a literal. Keeping the alias live means the
 * whole `comp → sys → ref` chain stays wired at runtime: a consumer can
 * override a single `--sys-*` (or `--ref-*`) custom property and every token
 * that aliases it re-themes, without touching component code. Literal values
 * (the `ref` tier, and any non-string leaf like `lineHeight`) pass through
 * unchanged. Composite strings (e.g. a shadow referencing a color) have each
 * `{…}` segment swapped independently, so partial references work too.
 */
function cssValue(token) {
  const original = token.original?.$value;
  if (typeof original === 'string' && original.includes('{')) {
    return original.replace(/\{([^}]+)\}/g, (_, ref) => `var(--${ref.split('.').join('-')})`);
  }
  return token.$value;
}

StyleDictionary.registerFormat({
  name: 'ghds/css',
  format: ({ dictionary, options }) => {
    const selector = options.selector ?? ':root';
    const lines = dictionary.allTokens.map(
      (token) => `  --${token.path.join('-')}: ${cssValue(token)};`,
    );
    return `${HEADER}${selector} {\n${lines.join('\n')}\n}\n`;
  },
});

StyleDictionary.registerFormat({
  name: 'ghds/esm',
  format: ({ dictionary, options }) =>
    `${HEADER}export const ${options.varName} = ${JSON.stringify(buildNested(dictionary.allTokens), null, 2)};\n`,
});

StyleDictionary.registerFormat({
  name: 'ghds/dts',
  format: ({ dictionary, options }) =>
    `${HEADER}export declare const ${options.varName}: ${toDts(buildNested(dictionary.allTokens))};\n`,
});

StyleDictionary.registerFormat({
  name: 'ghds/json',
  format: ({ dictionary }) => `${JSON.stringify(buildNested(dictionary.allTokens), null, 2)}\n`,
});

function makeStyleDictionary(theme) {
  return new StyleDictionary({
    log: { verbosity: 'silent', warnings: 'disabled' },
    source: [
      'src/ref/**/*.json',
      'src/sys/_shared.json',
      `src/sys/${theme}.json`,
      'src/comp/**/*.json',
    ],
    platforms: {
      css: {
        transforms: [],
        buildPath: 'dist/css/',
        files: [
          {
            destination: `_${theme}.css`,
            format: 'ghds/css',
            options: { selector: theme === 'light' ? ':root' : '[data-theme="dark"]' },
          },
        ],
      },
      ts: {
        transforms: [],
        buildPath: 'dist/ts/',
        files: [
          {
            destination: `${theme}.js`,
            format: 'ghds/esm',
            options: { varName: `${theme}Tokens` },
          },
          {
            destination: `${theme}.d.ts`,
            format: 'ghds/dts',
            options: { varName: `${theme}Tokens` },
          },
        ],
      },
      rn: {
        transforms: ['ghds/value/rn'],
        buildPath: 'dist/rn/',
        files: [
          {
            destination: `${theme}.js`,
            format: 'ghds/esm',
            options: { varName: `${theme}Tokens` },
          },
          {
            destination: `${theme}.d.ts`,
            format: 'ghds/dts',
            options: { varName: `${theme}Tokens` },
          },
        ],
      },
      json: {
        transforms: [],
        buildPath: 'dist/json/',
        files: [
          {
            destination: theme === 'light' ? 'tokens.json' : 'tokens.dark.json',
            format: 'ghds/json',
          },
        ],
      },
    },
  });
}

/** Inner `--var: value;` lines of a generated single-selector CSS block. */
function cssBody(css) {
  return css.slice(css.indexOf('{') + 1, css.lastIndexOf('}')).replace(/^\n+|\n+$/g, '');
}

async function main() {
  const dist = path.resolve('dist');
  await fs.rm(dist, { recursive: true, force: true });

  for (const theme of THEMES) {
    await makeStyleDictionary(theme).buildAllPlatforms();
  }

  // Combined CSS: light :root, dark attribute selector, dark prefers-color-scheme.
  const lightCss = await fs.readFile('dist/css/_light.css', 'utf8');
  const darkCss = await fs.readFile('dist/css/_dark.css', 'utf8');
  const darkBody = cssBody(darkCss);
  const mediaBody = darkBody
    .split('\n')
    .map((line) => `  ${line}`)
    .join('\n');
  // `:root` is the light default. `[data-theme="dark"]` (higher specificity) always wins.
  // The OS-preference fallback is scoped to `:root:not([data-theme])` so an explicit
  // `data-theme="light"` is NOT overridden by a dark OS setting.
  const combined = [
    HEADER,
    `:root {\n${cssBody(lightCss)}\n}`,
    '',
    `[data-theme="dark"] {\n${darkBody}\n}`,
    '',
    `@media (prefers-color-scheme: dark) {\n  :root:not([data-theme]) {\n${mediaBody}\n  }\n}`,
    '',
  ].join('\n');
  await fs.writeFile('dist/css/variables.css', combined);
  await fs.rm('dist/css/_light.css');
  await fs.rm('dist/css/_dark.css');

  // Barrel entries.
  const webIndex = `${HEADER}export { lightTokens, lightTokens as tokens } from './ts/light.js';\nexport { darkTokens } from './ts/dark.js';\n`;
  await fs.writeFile('dist/index.js', webIndex);
  await fs.writeFile('dist/index.d.ts', webIndex);

  const rnIndex = `${HEADER}export { lightTokens } from './light.js';\nexport { darkTokens } from './dark.js';\n`;
  await fs.writeFile('dist/rn/index.js', rnIndex);
  await fs.writeFile('dist/rn/index.d.ts', rnIndex);

  console.log('@ghds/tokens: built css, ts, rn, json for', THEMES.join(' + '));
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
